public class Angolo {
    private int gradi;
    private int primi;
    private int secondi;

    public Angolo(int gradi, int primi, int secondi){
        this.gradi = gradi;
        this.primi = primi;
        this.secondi = secondi;
    }

    public void setGradi(int gradi) {
        this.gradi = gradi;
    }

    public void setPrimi(int primi) {
        this.primi = primi;
    }

    public void setSecondi(int secondi) {
        this.secondi = secondi;
    }
}
